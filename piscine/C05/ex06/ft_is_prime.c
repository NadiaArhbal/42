int	ft_is_prime(int nb)
{
	int	i;
	int	cpt;

	i = 0;
	cpt = 1;
	if (nb <= 1)
		return (0);
	while (i < 2)
	{
		if (nb % cpt == 0)
		{
			i++;
		}
		cpt++;
	}
	cpt--;
	if (i == 2 && cpt != nb)
		return (0);
	else
		return (1);
}
